fn advance(c: char) -> f32 {
    if c == ' ' { 3.0 } else { (COLS + 1) as f32 }
}

/// Width in dot pitches.
fn width_units(text: &str) -> f32 {
    let w: f32 = text.chars().map(advance).sum();
    (w - 1.0).max(0.0)
}

/// Width of `text` drawn `height` tall.
pub fn width(text: &str, height: f32) -> f32 {
    width_units(text) * height / ROWS as f32
}

/// Whether every character of `text` has a dot-matrix glyph.
pub fn supports(text: &str) -> bool {
    text.chars().all(|c| c == ' ' || glyph(c).is_some())
}

/// Draws dot-matrix `text` anchored at `pos`. `bold` dots touch (titles); otherwise
/// they are spaced like a display (figures). Returns the occupied rectangle.
pub fn draw(
    painter: &Painter,
    pos: Pos2,
    align: egui::Align2,
    height: f32,
    text: &str,
    color: Color32,
    bold: bool,
) -> egui::Rect {
    let pitch = height / ROWS as f32;
    let size = egui::vec2(width_units(text) * pitch, height);
    let rect = align.anchor_size(pos, size);
    let radius = pitch * if bold { 0.5 } else { 0.36 };
    let mut x = rect.left();
    for c in text.chars() {
        if let Some(rows) = glyph(c) {
            for (r, row) in rows.iter().enumerate() {
                for (col, cell) in row.bytes().enumerate() {
                    if cell == b'#' {
                        let p = pos2(
                            x + col as f32 * pitch + pitch / 2.0,
                            rect.top() + r as f32 * pitch + pitch / 2.0,
                        );
                        painter.circle_filled(p, radius, color);
                    }
                }
            }
        }
        x += advance(c) * pitch;
    }
    rect
}

/// Menu bar glyph: a dot-matrix "X" in black on transparent, 36×36 px (shown at 18 pt).
pub fn menu_bar_png() -> Vec<u8> {
    const N: u32 = 36;
    let pattern = ["X...X", ".X.X.", "..X..", ".X.X.", "X...X"];
    let mut img = image::RgbaImage::new(N, N);
    for y in 0..N {
        for x in 0..N {
            let mut hits = 0;
            for s in 0..16 {
                let px = x as f32 + ((s % 4) as f32 + 0.5) / 4.0;
                let py = y as f32 + ((s / 4) as f32 + 0.5) / 4.0;
                let on = pattern.iter().enumerate().any(|(r, row)| {
                    row.bytes().enumerate().any(|(c, b)| {
                        let (cx, cy) = (4.0 + c as f32 * 7.0, 4.0 + r as f32 * 7.0);
                        let rad = if b == b'X' { 3.1 } else { 1.0 };
                        (px - cx).powi(2) + (py - cy).powi(2) <= rad * rad
                    })
                });
                if on {
                    hits += 1;
                }
            }
            img.put_pixel(x, y, image::Rgba([0, 0, 0, (hits * 255 / 16) as u8]));
        }
    }
    let mut out = std::io::Cursor::new(Vec::new());
    let _ = img.write_to(&mut out, image::ImageFormat::Png);
    out.into_inner()
}
